--[[
Writes lib/trial_data.lua from a CatsEye server checkout.

    luajit tools\gen_trial_data.lua <server root> lib\trial_data.lua

Reads scripts/enum/item.lua and scripts/globals/magian_data.lua. Each trial
becomes its number -> { total = numRequired, reward = rewardItem.itemId }.
Run it again when the server changes its trials.
]]

local root, out = arg[1], arg[2]
if root == nil or out == nil then
    io.stderr:write('usage: luajit tools\\gen_trial_data.lua <server root> <out file>\n')
    os.exit(1)
end

-- Every xi.* table but xi.item answers any field. Only the item ids are read.
local function stub()
    return setmetatable({}, {
        __index = function(t, k)
            local v = stub()
            rawset(t, k, v)
            return v
        end,
    })
end

local xi = stub()
local env = setmetatable({
    xi = xi,
    -- scripts/utils/common.lua
    set = function(list)
        local s = {}
        for _, v in ipairs(list) do
            s[v] = true
        end
        return s
    end,
}, { __index = _G })

local function run(path)
    local chunk = assert(loadfile(path))
    setfenv(chunk, env)
    chunk()
end

run(root .. '/scripts/enum/item.lua')
local items = rawget(xi, 'item')
assert(type(items) == 'table', 'scripts/enum/item.lua set no xi.item')
setmetatable(items, {
    __index = function(_, k)
        error('magian_data.lua names an item the enum lacks: ' .. tostring(k))
    end,
})
run(root .. '/scripts/globals/magian_data.lua')

local trials = xi.magian.trials
local ids = {}
for id in pairs(trials) do
    ids[#ids + 1] = id
end
table.sort(ids)

local lines = {}
local skipped = 0
for _, id in ipairs(ids) do
    local trial = trials[id]
    local total = tonumber(trial.numRequired)
    local reward = type(trial.rewardItem) == 'table' and tonumber(trial.rewardItem.itemId) or nil
    if total and total > 0 then
        if reward and reward > 0 then
            lines[#lines + 1] = string.format('    [%d] = { total = %d, reward = %d },', id, total, reward)
        else
            lines[#lines + 1] = string.format('    [%d] = { total = %d },', id, total)
        end
    else
        skipped = skipped + 1
    end
end

local header = table.concat({
    '--[[',
    'Tracker - each Magian trial\'s objective count and reward item id.',
    '',
    'Generated by tools/gen_trial_data.lua from CatsEye\'s',
    'scripts/globals/magian_data.lua (numRequired and rewardItem.itemId). Do',
    'not edit by hand. Run the tool again when the server changes its trials.',
    ']]',
    '',
    'return {',
}, '\n')

local f = assert(io.open(out, 'wb'))
f:write(header, '\n', table.concat(lines, '\n'), '\n}\n')
f:close()
print(string.format('%d trials written, %d skipped', #lines, skipped))
